public class pila{
    
    public static void push (Stack s, Data d){
        insert(s.L,d);
    }

    public static void pop (){
        if (s.L.head = NIL){
           System.out.println("Error");
        }
        else {
            d = s.L.head.Data;
            delete(s.L.d);
            return d;
        }
    }

}